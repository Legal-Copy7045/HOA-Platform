#!/usr/bin/env bash
# Creates /opt/hoa-portal/.env on the POC VM with freshly generated secrets.
#
#   cd /opt/hoa-portal && bash infra/poc/make-env.sh
#
# Asks for the Cloudflare tunnel token (typing is hidden). Everything else is
# generated here and never leaves the VM. Refuses to overwrite an existing
# .env. Afterwards, copy the file's secrets into the HOA password manager.
set -euo pipefail
trap 'echo "ERROR: make-env.sh stopped at line $LINENO (exit $?)." >&2' ERR

cd "$(dirname "$0")/../.."
[ -f docker-compose.tunnel.yml ] || { echo "Run from the portal checkout." >&2; exit 1; }
if [ -e .env ]; then
  echo ".env already exists; nothing changed. Move it aside first to regenerate." >&2
  exit 1
fi

HOSTNAME_PUBLIC="${HOSTNAME_PUBLIC:-portal-dev.oakcreekhoa.com}"
# Hex only: these end up inside connection URLs.
secret() { openssl rand -hex "$1"; }

read -r -s -p "Paste the Cloudflare tunnel token (input hidden), then Enter: " TUNNEL_TOKEN
echo
[ "${#TUNNEL_TOKEN}" -ge 100 ] || { echo "That does not look like a tunnel token (too short)." >&2; exit 1; }
read -r -p "POC catch-all email for all outgoing mail (blank = none for now): " REDIRECT_TO

umask 077
cat > .env <<ENV
# Generated by infra/poc/make-env.sh on $(date -u +%Y-%m-%dT%H:%MZ). Secrets: keep
# only here and in the HOA password manager. File mode must stay 600.

DJANGO_SECRET_KEY=$(secret 40)
DJANGO_ALLOWED_HOSTS=${HOSTNAME_PUBLIC}
DJANGO_CSRF_TRUSTED_ORIGINS=https://${HOSTNAME_PUBLIC}
PORTAL_BASE_URL=https://${HOSTNAME_PUBLIC}
SITE_NAME=Oak Creek Farms HOA
TIME_ZONE=America/New_York
LOG_LEVEL=INFO
SECURE_HSTS_SECONDS=3600

AUDIT_HASH_KEY=$(secret 32)
AUDIT_IP_RETENTION_DAYS=365

POSTGRES_SUPERUSER_PASSWORD=$(secret 24)
HOA_DB_NAME=hoa
HOA_OWNER_DB_USER=hoa_owner
HOA_OWNER_DB_PASSWORD=$(secret 24)
HOA_APP_DB_USER=hoa_app
HOA_APP_DB_PASSWORD=$(secret 24)

S3_ENDPOINT_URL=http://seaweedfs:8333
S3_BUCKET=hoa-private
S3_ACCESS_KEY_ID=$(secret 10)
S3_SECRET_ACCESS_KEY=$(secret 24)
S3_REGION=us-east-1

# Email: fill in the Hostinger mailbox before invitations are used (step 6).
EMAIL_HOST=smtp.hostinger.com
EMAIL_PORT=465
EMAIL_USE_SSL=true
EMAIL_USE_TLS=false
EMAIL_HOST_USER=
EMAIL_HOST_PASSWORD=
DEFAULT_FROM_EMAIL=Oak Creek Farms HOA <portal@oakcreekhoa.com>
EMAIL_REDIRECT_ALL_TO=${REDIRECT_TO}

# POC only: fictional demo data allowed. Never true in production.
SEED_DEMO_ALLOWED=true
# Marks this deployment as the POC; production ignores SEED_DEMO_ALLOWED otherwise.
DEPLOYMENT_STAGE=poc
# Decision D21: one board member may record seats on the POC (production: true).
BOARD_SEAT_SECOND_APPROVAL=false

# Malware scanning with the ClamAV container (decision D21).
DOCUMENT_SCANNER=clamd
DOCUMENT_CLAMD_ADDRESS=clamav:3310
DOCUMENT_REQUIRE_CLEAN_SCAN=true

OFFICERS_REQUIRE_BOARD_SEAT=true
OFFICERS_REQUIRE_BOARD_SEAT_CITATION=

# Installable app and alerts (optional; the board switches "push" and "sms"
# on in Admin -> Features). Push keys: docker compose exec web python manage.py
# generate_vapid_keys. Restart the portal after filling these in.
VAPID_PUBLIC_KEY=
VAPID_PRIVATE_KEY=
VAPID_SUBJECT=
# PUSH_ALLOWED_HOSTS=   (unset = the usual browser push services)
SMS_PROVIDER=none
SMS_ACCOUNT_SID=
SMS_AUTH_TOKEN=
SMS_FROM=
# SMS_API_BASE=https://api.twilio.com

# Bank feed (optional; docs/runbook.md "Bank feed (Teller, free tier)").
BANK_FEED_TOKEN_KEY=$(secret 32)
TELLER_APPLICATION_ID=
TELLER_ENVIRONMENT=development
TELLER_CERTIFICATE_B64=
TELLER_PRIVATE_KEY_B64=

# USPS tracking (optional; sudo bash infra/poc/set-usps.sh fills these in).
USPS_IV_ENVIRONMENT=cat
USPS_IV_USERNAME=
USPS_IV_PASSWORD=

# Bounced email (optional; sudo bash infra/poc/set-bounce-mailbox.sh fills these in).
BOUNCE_IMAP_HOST=
BOUNCE_IMAP_PORT=993
BOUNCE_IMAP_USER=
BOUNCE_IMAP_PASSWORD=
BOUNCE_IMAP_FOLDER=INBOX
BOUNCE_RETURN_PATH=

TUNNEL_TOKEN=${TUNNEL_TOKEN}
ENV
chmod 600 .env
unset TUNNEL_TOKEN
echo "Created .env (mode 600). Next: sudo bash infra/poc/start-portal.sh"
